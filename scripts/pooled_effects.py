#!/usr/bin/env python3
"""The impression-side checks, judged by a pooled estimate over 10 seeds.

    ./do pooled-effects

Since ADR 0045 every sale is a purchased showing, so a null that switches an
impression effect off re-draws whole histories: orders, stars, labels, stock,
experiences, churn. The per-seed noise model no longer holds. Each check's
per-seed value is computed as `scripts/planted_effects.py` computes it; the
pooled estimate and its 95 % interval are across the seeds. Design:
docs/verification/actionable-states-prereg.md (amendment: pooled judging).
Writes docs/verification/actionable-states-pooled.md.
"""
from __future__ import annotations

import math
import multiprocessing
import statistics
import sys
from pathlib import Path

from scripts.planted_effects import CHECKS, GE, LE, _measure, generate

SEEDS = (42, 7, 99, 1, 2, 3, 11, 13, 17, 23)
POOLED = ("P6", "P6 high", "P7", "P7 high", "P8", "P8 high", "P9", "P9 high", "P10", "V1",
          "R1", "R2a", "R2b", "R5", "O2", "O3a", "O3b")
T_975_9 = 2.262            # Student's t, 9 degrees of freedom
PROCESSES = 5              # each generation holds a few GB
REPORT = Path(__file__).resolve().parent.parent / "docs/verification/actionable-states-pooled.md"
CHECKS_BY_ID = {c.id: c for c in CHECKS}


def values_for_seed(seed: int) -> dict[str, float]:
    """Each pooled check's value on one seed: planted against its null."""
    checks = [CHECKS_BY_ID[i] for i in POOLED]
    planted = _measure(generate(seed, None), {m for c in checks for m in c.metrics})
    values = {c.id: c.value(planted, {}) for c in checks if c.null is None}
    for null_name in sorted({c.null for c in checks if c.null}):
        mine = [c for c in checks if c.null == null_name]
        null = _measure(generate(seed, null_name), {m for c in mine for m in c.metrics})
        values.update({c.id: c.value(planted, null) for c in mine})
    print(f"seed {seed}: " + "  ".join(f"{k} {v:.3f}" for k, v in values.items()), flush=True)
    return values


def pooled(check_id: str, values: list[float]) -> tuple[float, float, float, bool]:
    """(estimate, interval low, interval high, passed) under the amendment's rule."""
    check = CHECKS_BY_ID[check_id]
    if check.form == "planted":           # O3b: a count, every seed must read 0
        mean = statistics.mean(values)
        return mean, min(values), max(values), check.compare(mean, check.margin)
    logs = [math.log(v) for v in values]
    centre, half = statistics.mean(logs), T_975_9 * statistics.stdev(logs) / math.sqrt(len(logs))
    estimate, low, high = math.exp(centre), math.exp(centre - half), math.exp(centre + half)
    if check.compare is GE:
        return estimate, low, high, estimate >= check.margin and low > 1.0
    assert check.compare is LE, check_id
    return estimate, low, high, estimate <= check.margin and high < 1.0


def main() -> int:
    with multiprocessing.get_context("fork").Pool(PROCESSES) as pool:
        per_seed = dict(zip(SEEDS, pool.map(values_for_seed, SEEDS)))
    rows = []
    for check_id in POOLED:
        values = [per_seed[s][check_id] for s in SEEDS]
        rows.append((check_id, values, *pooled(check_id, values)))
    _write_report(rows)
    passed = sum(r[-1] for r in rows)
    print(f"\n{passed} of {len(rows)} pass (pooled). Report: {REPORT.relative_to(REPORT.parents[2])}")
    return 0 if passed == len(rows) else 1


def _write_report(rows) -> None:
    head = " | ".join(str(s) for s in SEEDS)
    lines = [
        "# Impression-side checks, pooled over 10 seeds (ADR 0045)",
        "",
        "Generated by `./do pooled-effects` (`scripts/pooled_effects.py`). Each seed's value is",
        "the registered check's (planted ÷ its null). Ratios pool as a geometric mean with a",
        "95 % interval across seeds (t, 9 degrees of freedom); a check passes when the estimate",
        "meets its threshold and the interval excludes the null's 1.0. O3b counts slots, and",
        "every seed must read 0. Rule: `actionable-states-prereg.md`, amendment on pooled",
        "judging. The three-seed table stays in `actionable-states-data.md`.",
        "",
        f"| check | what | threshold | pooled | 95 % interval | result | {head} |",
        "|:--|:--|:--|--:|:--|:--|" + "--:|" * len(SEEDS),
    ]
    for check_id, values, estimate, low, high, passed in rows:
        c = CHECKS_BY_ID[check_id]
        threshold = f"{'≥' if c.compare is GE else '≤'} {c.margin}"
        per = " | ".join(f"{v:.3f}" for v in values)
        lines.append(f"| {c.id} | {c.title} | {threshold} | {estimate:.3f} | {low:.3f}–{high:.3f} | "
                     f"{'pass' if passed else '**fail**'} | {per} |")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
