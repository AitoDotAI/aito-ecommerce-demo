"""Judge data release 3a's effects on three seeds (docs/verification/release3a-prereg.md).

Each effect is read as a ratio inside one generation, so no null generation is needed; it is judged on the
mean of the seeds (a banner is about 30 products, so one seed is noisy). One process per seed:
a generation patches module-level state. Writes docs/verification/release3a-data.md.

    python3 -m scripts.release3_effects
"""
from __future__ import annotations

import multiprocessing
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from scripts import listing_effect_metrics as m
from scripts import planted_effect_metrics as metrics
from scripts.planted_effects import SEEDS, generate

REPORT = Path(__file__).resolve().parent.parent / "docs/verification/release3a-data.md"


@dataclass(frozen=True)
class Range:
    id: str
    title: str
    measure: Callable[[metrics.Fixtures], float]
    low: float | None = None
    high: float | None = None

    def passes(self, value: float) -> bool:
        return (self.low is None or value >= self.low) and (self.high is None or value <= self.high)

    def expected(self) -> str:
        return " – ".join(("" if self.low is None else f"≥ {self.low}", "" if self.high is None else f"≤ {self.high}")).strip(" –")


CHECKS = [
    Range("Q3", "offer 20 %+: purchases per showing ÷ click-through", m.offer_purchase_over_click, low=1.2),
    Range("Q3a", "offer 20 %+: click-through ratio", m.offer_click_through, 1.15, 1.6),
    Range("Q3b", "offer 20 %+: units ratio (reported; O2 judges it against a null)", m.offer_units, low=1.2),
    Range("Q2", "list price: the elasticity the units imply", m.list_price_elasticity, -2.5, -0.5),
    Range("Q2a", "list price: purchase response ÷ click response", m.list_price_purchase_over_click, low=1.0),
    Range("Q4 ctr", "4+ pictures ÷ 0–1: click-through", lambda fx: m.images(fx, "ctr"), 1.1, 1.3),
    Range("Q4 buy", "4+ pictures ÷ 0–1: purchases per click", lambda fx: m.images(fx, "per click"), low=1.02),
    Range("Q5 buy", "rich ÷ thin description: purchases per click", lambda fx: m.description(fx, "per click"), low=1.1),
    Range("Q5 ctr", "rich ÷ thin description: click-through", lambda fx: m.description(fx, "ctr"), 0.9, 1.1),
    Range("Q6 showings", "banner ÷ none: showings per product-month", m.banner_showings, low=1.4),
    Range("Q6 ctr", "banner ÷ none: click-through", lambda fx: m.ads(fx, "ctr"), 1.0, 1.35),
    Range("Q6 buy", "banner ÷ none: purchases per click", lambda fx: m.ads(fx, "per click"), 0.85, 1.15),
]


def judge_seed(seed: int) -> list[tuple[str, int, float, bool]]:
    fx = generate(seed, None)
    try:
        return [(c.id, seed, (value := c.measure(fx)), c.passes(value)) for c in CHECKS]
    finally:
        metrics.clear_caches()
        shutil.rmtree(fx.dir)


def main() -> int:
    with multiprocessing.get_context("fork").Pool(len(SEEDS)) as pool:
        rows = [row for seed_rows in pool.map(judge_seed, SEEDS) for row in seed_rows]
    lines = ["# Data release 3a: planted effects (ADRs 0049, 0050)", "",
             "Generated by `python3 -m scripts.release3_effects`. One ratio per seed, judged against the ranges of",
             "`release3a-prereg.md`.", "", "| Check | What | Expected | " + " | ".join(f"seed {s}" for s in SEEDS) + " | mean |",
             "|:--|:--|:--|" + "--:|" * (len(SEEDS) + 1)]
    verdicts = []
    for c in CHECKS:
        mine = {seed: (value, ok) for cid, seed, value, ok in rows if cid == c.id}
        mean = sum(v for v, _ in mine.values()) / len(mine)
        cells = " | ".join(f"{mine[s][0]:.2f}" for s in SEEDS)
        lines.append(f"| {c.id} | {c.title} | {c.expected()} | {cells} | **{mean:.2f} {'✓' if c.passes(mean) else '✗'}** |")
        verdicts.append(c.passes(mean))
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\n{sum(verdicts)} of {len(verdicts)} checks pass on the mean of {len(SEEDS)} seeds.")
    return 0 if all(verdicts) else 1


if __name__ == "__main__":
    raise SystemExit(main())
